  function getLang() {
    return localStorage.getItem(KEY_LANG) === "en" ? "en" : "tr";
  }

  function setLang(lang) {
    localStorage.setItem(KEY_LANG, lang === "en" ? "en" : "tr");
    location.reload();
  }

  function getTheme() {
    return localStorage.getItem(KEY_THEME) === "dark" ? "dark" : "light";
  }

  function setTheme(mode) {
    localStorage.setItem(KEY_THEME, mode === "dark" ? "dark" : "light");
    applyTheme();
    // Admin topbar uses #topbarAppControls; öğrenci sayfaları #studentTopbarControls. İkisini birden
    // çağırmak adminde tema+ dil bloklarını iki kez gösterir.
    if (document.getElementById("topbarAppControls")) {
      if (typeof window.mountTopbarAppControls === "function") window.mountTopbarAppControls();
    } else if (typeof window.mountStudentTopbarControls === "function") {
      window.mountStudentTopbarControls();
    }
  }

  function toggleTheme() {
    setTheme(getTheme() === "dark" ? "light" : "dark");
  }

  function applyTheme() {
    var dark = getTheme() === "dark";
    document.documentElement.setAttribute("data-theme", dark ? "dark" : "light");
    document.documentElement.lang = getLang() === "en" ? "en" : "tr";
  }

  function formatTpl(str, vars) {
    if (!vars || typeof vars !== "object") return str;
    return String(str).replace(/\{(\w+)\}/g, function (_, k) {
      return vars[k] != null ? String(vars[k]) : "";
    });
  }

  function t(key, vars) {
    var lang = getLang();
    var v = dict[lang] && dict[lang][key];
    if (v == null) v = dict.tr[key];
    if (v == null) return key;
    return formatTpl(v, vars);
  }

  function applyDataI18n(root) {
    root = root || document;
    root.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (!key) return;
      var vars = null;
      var j = el.getAttribute("data-i18n-vars");
      if (j) {
        try {
          vars = JSON.parse(j);
        } catch (e) {}
      }
      el.textContent = t(key, vars);
    });
    root.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-html");
      if (key) el.innerHTML = t(key);
    });
    root.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-placeholder");
      if (key) el.placeholder = t(key);
    });
    root.querySelectorAll("[data-i18n-title]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-title");
      if (key) el.title = t(key);
    });
  }

  function bootI18n() {
    applyDataI18n(document);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", bootI18n);
  } else {
    bootI18n();
  }

